/**
 * Generates src/lib/animal-compare/scientific-names.ts from the real
 * /animals/<slug>/page.tsx files. The value is EXTRACTED, never authored:
 * every entry is the exact string the profile page already renders in its H1.
 * Profiles with no scientificName prop are simply absent from the map, and the
 * taxonomy block omits the name rather than inventing one.
 */
import fs from "node:fs";
import path from "node:path";

const REPO = "/Users/titan/faunahub-com";
const ANIMALS = path.join(REPO, "src/app/animals");

const entries = [];
for (const slug of fs.readdirSync(ANIMALS).sort()) {
  const file = path.join(ANIMALS, slug, "page.tsx");
  if (!fs.existsSync(file)) continue;
  const m = fs.readFileSync(file, "utf8").match(/scientificName="([^"]+)"/);
  if (!m) continue;
  entries.push([slug, m[1]]);
}

const body = entries
  .map(([s, n]) => `  "${s}": ${JSON.stringify(n)},`)
  .join("\n");

const out = `/**
 * Scientific names for animals that have one on their profile page.
 *
 * GENERATED by scripts/generate-scientific-names.mjs from the
 * \`scientificName\` prop of each src/app/animals/<slug>/page.tsx. Nothing here
 * is authored: each value is the exact string that profile already displays, so
 * the comparison pages and the profile can never disagree.
 *
 * Absence is meaningful. ${642 - entries.length} profiles carry no scientific name — usually
 * group-level pages where a single binomial would be wrong — and those animals
 * are simply omitted from the taxonomy block rather than given an invented one.
 *
 * Re-run: node scripts/generate-scientific-names.mjs
 */

export const SCIENTIFIC_NAMES: Record<string, string> = {
${body}
};

/** The displayed scientific name for an animal, or undefined if it has none. */
export function scientificNameFor(slug: string): string | undefined {
  return SCIENTIFIC_NAMES[slug];
}
`;

fs.writeFileSync(path.join(REPO, "src/lib/animal-compare/scientific-names.ts"), out);
console.log("entries written:", entries.length);
