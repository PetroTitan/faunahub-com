export const BACKLOG_COUNT = COMPARISON_BACKLOG.length;

export function backlogByStatus(status: BacklogStatus): BacklogCandidate[] {
  return COMPARISON_BACKLOG.filter((c) => c.status === status);
}

/** Every pair key in the backlog, published or not. */
export function backlogPairKeys(): Set<string> {
  return new Set(COMPARISON_BACKLOG.map((c) => c.canonicalPairKey));
}

/** Pair keys that must NOT be publicly routable. */
export function unpublishedPairKeys(): Set<string> {
  return new Set(
    COMPARISON_BACKLOG.filter((c) => c.status !== "published").map((c) => c.canonicalPairKey),
  );
}

/** Precomputed lookup so promotion checks never rescan the array. */
const BY_PAIR_KEY = new Map(COMPARISON_BACKLOG.map((c) => [c.canonicalPairKey, c]));

export function backlogByPairKey(pairKey: string): BacklogCandidate | undefined {
  return BY_PAIR_KEY.get(pairKey);
}

export function statusDistribution(): Record<string, number> {
  const out: Record<string, number> = {};
  for (const c of COMPARISON_BACKLOG) out[c.status] = (out[c.status] ?? 0) + 1;
  return out;
}
