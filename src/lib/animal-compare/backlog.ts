  proposedCategory: string;
  relationship: string;
  searchIntent: string;
  sourceReadiness: SourceReadiness;
  profileReadiness: ProfileReadiness;
  qualityRisk: QualityRisk;
  status: BacklogStatus;
  /** Why it cannot be built yet. Set when status is blocked-*. */
  blockerReason?: string;
  /** Why it will not be built. Set when status is "rejected". */
  rejectionReason?: string;
  /** The real public slug. Set if and only if status is "published". */
  publishedSlug?: string;
  reviewedAt: string;
  publishedAt?: string;
  note: string;
